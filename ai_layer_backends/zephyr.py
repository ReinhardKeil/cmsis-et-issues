"""Render a Zephyr AI layer from the shared MLOps description and export."""

from pathlib import Path
import re

from . import ExportedModel, selected_symbols
from .cmsis import executorch_pack

CMAKE = '''# Generated by create_ai_layer.py -- do not edit.
# Include this directory before find_package(Zephyr): Kconfig is processed there.
if(TARGET zephyr_interface)
  message(FATAL_ERROR
    "add_subdirectory(ai_layer) must precede find_package(Zephyr) so the AI layer configuration is merged."
  )
endif()

list(APPEND EXTRA_CONF_FILE
  "${CMAKE_CURRENT_SOURCE_DIR}/components.conf"
  "${CMAKE_CURRENT_SOURCE_DIR}/operators.conf"
)
set(EXTRA_CONF_FILE "${EXTRA_CONF_FILE}" PARENT_SCOPE)

add_library(ai_layer INTERFACE)
target_sources(ai_layer INTERFACE "${CMAKE_CURRENT_SOURCE_DIR}/model_pte.c")
target_include_directories(ai_layer INTERFACE "${CMAKE_CURRENT_SOURCE_DIR}")

# Zephyr creates app and identifies the compiler during find_package(), after
# this directory is processed. Decide source ownership when the parent finishes.
function(_ai_layer_link_app layer_target)
  if(CMAKE_CXX_COMPILER_ID STREQUAL "ARMClang")
    # armlink also propagates interface sources to intermediate ELF targets.
    # Compile the model in app only to avoid duplicate model definitions.
    get_target_property(_ai_sources "${layer_target}" INTERFACE_SOURCES)
    if(_ai_sources)
      target_sources(app PRIVATE ${_ai_sources})
      set_property(TARGET "${layer_target}" PROPERTY INTERFACE_SOURCES "")
    endif()
  endif()
  target_link_libraries(app PRIVATE "${layer_target}")
endfunction()

get_directory_property(_ai_layer_parent PARENT_DIRECTORY)
cmake_language(DEFER DIRECTORY "${_ai_layer_parent}"
  CALL _ai_layer_link_app ai_layer
)
'''

COMPONENTS = '''# Generated by create_ai_layer.py -- do not edit.
CONFIG_CMSIS_EXECUTORCH=y

CONFIG_CMSIS_EXECUTORCH_RUNTIME=y
CONFIG_CMSIS_EXECUTORCH_KERNEL_UTILS=y
CONFIG_CMSIS_EXECUTORCH_KERNEL_REGISTRATION=y
CONFIG_CMSIS_EXECUTORCH_BACKEND_ETHOS_U=y
'''


def render(mlops_file: Path, mlops: dict, model: ExportedModel) -> tuple[Path, dict[str, str]]:
    """Return the CMake entry point and config fragments using the selected pack."""
    pack = executorch_pack(mlops_file)
    symbols = selected_symbols(
        model.operators,
        (pack / "src/registration/RegisterAllKernels.cpp").read_text(),
        "RTE_ML_EXECUTORCH_OP_",
    )
    kconfig = (pack / "zephyr/Kconfig").read_text()
    available = set(re.findall(r"(?m)^config CMSIS_EXECUTORCH_OP_([A-Z0-9_]+)\s*$", kconfig))
    if set(symbols) - available:
        raise ValueError(f"operator Kconfig options missing for {sorted(set(symbols) - available)}")
    operators = "# Generated by create_ai_layer.py -- do not edit.\n" + "".join(
        f"CONFIG_CMSIS_EXECUTORCH_OP_{symbol}=y\n" for symbol in symbols
    )
    return mlops_file.parent / "ai_layer/CMakeLists.txt", {
        "CMakeLists.txt": CMAKE,
        "components.conf": COMPONENTS,
        "operators.conf": operators,
    }
