"""Render a Zephyr AI layer from the shared MLOps description and export."""

from pathlib import Path
import re

from . import ExportedModel, selected_symbols
from .cmsis import executorch_pack

CMAKE = '''# Generated by create_ai_layer.py -- do not edit.
# Include this directory after find_package(Zephyr) creates the app target.
target_sources(app PRIVATE "${CMAKE_CURRENT_SOURCE_DIR}/model_pte.c")
target_include_directories(app PRIVATE "${CMAKE_CURRENT_SOURCE_DIR}")
'''

COMPONENTS = '''# Generated by create_ai_layer.py -- do not edit.
CONFIG_CMSIS_EXECUTORCH=y

CONFIG_CMSIS_EXECUTORCH_RUNTIME=y
CONFIG_CMSIS_EXECUTORCH_KERNEL_UTILS=y
CONFIG_CMSIS_EXECUTORCH_KERNEL_REGISTRATION=y
CONFIG_CMSIS_EXECUTORCH_BACKEND_ETHOS_U=y
'''


def render(mlops_file: Path, mlops: dict, model: ExportedModel) -> tuple[Path, dict[str, str]]:
    """Return the CMake entry point and config fragments using the selected pack."""
    pack = executorch_pack(mlops_file)
    symbols = selected_symbols(
        model.operators,
        (pack / "src/registration/RegisterAllKernels.cpp").read_text(),
        "RTE_ML_EXECUTORCH_OP_",
    )
    kconfig = (pack / "zephyr/Kconfig").read_text()
    available = set(re.findall(r"(?m)^config CMSIS_EXECUTORCH_OP_([A-Z0-9_]+)\s*$", kconfig))
    if set(symbols) - available:
        raise ValueError(f"operator Kconfig options missing for {sorted(set(symbols) - available)}")
    operators = "# Generated by create_ai_layer.py -- do not edit.\n" + "".join(
        f"CONFIG_CMSIS_EXECUTORCH_OP_{symbol}=y\n" for symbol in symbols
    )
    return mlops_file.parent / "ai_layer/CMakeLists.txt", {
        "CMakeLists.txt": CMAKE,
        "components.conf": COMPONENTS,
        "operators.conf": operators,
    }
